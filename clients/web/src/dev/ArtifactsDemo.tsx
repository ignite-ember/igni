export function ArtifactsDemo() {
  const [log, setLog] = useState<string[]>([]);
  // The share panel is a popover now, so the demo has to give it
  // something to hang off — the frame it used to sit inside.
  const shareAnchor = useRef<HTMLDivElement>(null);
  const [shareAt, setShareAt] = useState<{
    left: number;
    right: number;
    top: number;
    bottom: number;
  } | null>(null);

  useEffect(() => {
    const box = shareAnchor.current?.getBoundingClientRect();
    if (box) setShareAt({ left: box.left, right: box.right, top: box.top, bottom: box.bottom });
  }, []);

  const note = (line: string) =>
    setLog((prev) => [...prev.slice(-11), line]);

  // Stable across renders. Built inline, it got a new identity every
  // time the log updated — and the panels key their fetch effects on
  // `client`, so each RPC re-triggered the effect that made it. The
  // stale list sat on "Checking…" forever, fetching in a loop.
  const client = useMemo(
    () => ({
      rpc: async (method: string, args?: Record<string, unknown>) => {
        setLog((prev) => [...prev.slice(-11), `${method}(${args ? JSON.stringify(args) : ""})`]);
        // A beat, so spinners and disabled states are visible rather
        // than resolving before they paint.
        await new Promise((r) => setTimeout(r, 180));
        if (method === "artifact_stale") return STALE_ROWS;
        if (method === "artifact_compare") return COMPARE;
        if (method === "artifact_ask" || method === "artifact_run_cypher") return ASK_RESULT;
        if (method === "artifact_share") {
          return {
            url: "https://igni.acme.test/a/4224ef722a7e4a6890",
            version: 3,
            error: "",
          };
        }
        return null;
      },
    }),
    [],
  ) as never;

  return (
    <div className="demo-page">
      <h1 className="demo-title">Artifacts — UI sandbox</h1>
      <p className="demo-sub">
        Canned data. No backend, no Neo4j. Every RPC the controls send is
        logged at the bottom.
      </p>

      <section className="demo-block">
        <h2 className="demo-h2">Share</h2>
        <p className="demo-note">
          Each option states who it reaches. “Domain” is not a description;
          “anyone whose account email shares yours” is — and this is one click
          that can put a document in front of a company.
        </p>
        <div className="demo-frame" ref={shareAnchor}>
          {/* Anchored to this frame rather than to a control: the
              demo has nothing that opens it, and a popover with
              nothing to point at renders nothing at all. */}
          <ArtifactShareDialog
            client={client}
            artifactId="826de04b1ae70098"
            name="Auth model"
            at={shareAt}
            onClose={() => note("share: closed")}
          />
        </div>
      </section>

      <section className="demo-block">
        <h2 className="demo-h2">Needs attention</h2>
        <p className="demo-note">
          Opened from a count in the panel header, because a number in a status
          line is not a call to action. “What changed” fetches the pinned→head
          diff on demand.
        </p>
        <div className="demo-frame">
          <ArtifactStaleReview
            client={client}
            onOpenArtifact={(id) => note(`open artifact ${id}`)}
          />
        </div>
      </section>

      <section className="demo-block">
        <h2 className="demo-h2">A document</h2>
        <p className="demo-note">
          A reading column, muted section headings, and air instead of boxes —
          measured against Claude’s artifact viewer. Code is the only filled
          surface.
        </p>
        <div className="demo-frame">
          <DocumentPreview />
        </div>
      </section>

      <section className="demo-block">
        <h2 className="demo-h2">Ask the graph</h2>
        <p className="demo-note">
          Type a question, the session’s own model writes the Cypher, it runs
          locally. The query is shown and editable — that is the control, not
          debug output. Press Ask to populate.
        </p>
        <div className="demo-frame">
          <ArtifactGraphSearch
            client={client}
            onOpenArtifact={(id) => note(`open artifact ${id}`)}
          />
        </div>
      </section>

      <section className="demo-block">
        <h2 className="demo-h2">Lineage, with unreviewed captures</h2>
        <p className="demo-note">
          A confirmed source raises a staleness warning when it moves; a
          captured one does not until somebody says it is real. “Not a source”
          is not a delete — re-reading would re-capture it, and the same
          judgement would be asked for again every session.
        </p>
        <div className="demo-frame">
          <LineagePreview onAct={note} />
        </div>
      </section>

      <section className="demo-block">
        <h2 className="demo-h2">RPC log</h2>
        <pre className="demo-log">
          {log.length ? log.join("\n") : "(interact with the controls above)"}
        </pre>
      </section>
    </div>
  );
}

/**
 * A document as the panel draws it.
 *
 * Reproduced here rather than mounted from `ArtifactPanel` because
 * that component fetches a document, its versions and its lineage
 * before it renders anything. The markup and classes are the same.
 */
function DocumentPreview() {
  return (
    <article className="kb-doc">
      <header className="kb-doc-head">
        <h2 className="kb-doc-title">Auth model</h2>
        <p className="kb-doc-attribution">dmytro · v3 · 2h ago</p>
      </header>
      <div className="kb-doc-body markdown-body">
        <h1>Auth model</h1>
        <p>
          Auth is a signed JWT, not a session cookie. It expires in 15 minutes
          and is refreshed by an <code>httpOnly</code> cookie with{" "}
          <code>SameSite=Lax</code>.
        </p>
        <h2>Why it changed</h2>
        <p>
          The session cookie could not be revoked without a database read on
          every request, and the read was the thing that fell over first under
          load. A short-lived token moves the cost to refresh time, which
          happens once every fifteen minutes rather than once per request.
        </p>
        <h2>What still checks the denylist</h2>
        <ul>
          <li>
            Refresh, because a stolen refresh cookie is the only credential
            worth revoking.
          </li>
          <li>Admin routes, where the fifteen-minute window is too long.</li>
        </ul>
        <h2>The claim set</h2>
        <pre>
          <code>{`{ "sub": "user_id", "exp": 900, "scope": ["read", "write"] }`}</code>
        </pre>
        <p>Anything not in that set is looked up, not trusted.</p>
      </div>
      <LineagePreview onAct={() => {}} />
    </article>
  );
}

/**
 * The lineage list as the document page draws it.
 *
 * Reproduced here rather than mounted from `ArtifactPanel` because
 * that component owns a document fetch, a version fetch and a
 * lineage fetch before it renders anything — three stubs to see one
 * list. The markup and classes are the same.
 */
function LineagePreview({ onAct }: { onAct: (line: string) => void }) {
  const [reviewed, setReviewed] = useState<Record<string, string>>({});

  const verdict = (id: string, choice: string) => {
    onAct(`artifact_${choice}_source({"id":"886c33de30593dd3","source_id":"${id}"})`);
    setReviewed((prev) => ({ ...prev, [id]: choice }));
  };

  return (
    <div className="kb-detail">
      <section className="kb-lineage">
        <h3 className="kb-lineage-heading">Built on</h3>
        <ul className="kb-lineage-rows">
          <li className="kb-row kb-row-stale">
            <span className="kb-row-name">Auth model</span>
            <span className="kb-row-n">v1</span>
            <span className="kb-row-note">source now at v3</span>
          </li>
          <li className="kb-row">
            <span className="kb-row-name">Error taxonomy</span>
            <span className="kb-row-n">v2</span>
            <span className="kb-row-note">up to date</span>
          </li>
        </ul>
      </section>

      <section className="kb-lineage">
        <h3 className="kb-lineage-heading">Captured, not confirmed</h3>
        <ul className="kb-lineage-rows">
          {[
            { id: "c1", name: "Rate limiting notes", v: 4 },
            { id: "c2", name: "Postgres migration log", v: 1 },
          ].map((row) =>
            reviewed[row.id] ? (
              <li key={row.id} className="kb-row">
                <span className="kb-row-name">{row.name}</span>
                <span className="kb-row-n">v{row.v}</span>
                <span className="kb-row-note">
                  {reviewed[row.id] === "confirm" ? "confirmed" : "not a source"}
                </span>
              </li>
            ) : (
              <li key={row.id} className="kb-row kb-row-candidate">
                <span className="kb-row-name">{row.name}</span>
                <span className="kb-row-n">v{row.v}</span>
                <button
                  className="btn btn-xs"
                  onClick={() => verdict(row.id, "confirm")}
                >
                  Confirm
                </button>
                <button
                  className="btn btn-xs btn-quiet"
                  onClick={() => verdict(row.id, "dismiss")}
                >
                  Not a source
                </button>
              </li>
            ),
          )}
        </ul>
      </section>

      <section className="kb-lineage">
        <h3 className="kb-lineage-heading">Depended on by</h3>
        <ul className="kb-lineage-rows">
          <li className="kb-row">
            <span className="kb-row-name">Session expiry runbook</span>
            <span className="kb-row-n">v1</span>
            <span className="kb-row-note" />
          </li>
        </ul>
      </section>
    </div>
  );
}
