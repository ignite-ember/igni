/**
 * UI sandbox for the artifact surfaces.
 *
 * Reachable at ``?demo=artifacts`` (see ``main.tsx``). Renders the
 * four controls that carry the feature — share, stale review, the
 * graph-search result, and the lineage list with its unreviewed
 * captures — against a canned client. No BE, no Neo4j, no published
 * documents needed, so visual iteration is fast and the same every
 * time.
 *
 * What this exists to make visible:
 *
 *   • **Share states its reach, not its name.** "Everyone at my
 *     company" over "anyone whose account email shares yours". This
 *     is one click that can put a document in front of a company, and
 *     a label alone is a claim the reader cannot check. There is no
 *     "my organisation" option — every account gets an org created
 *     for it at sign-up, so that one shared with nobody.
 *   • **A stale row leads with the gap.** "pinned to v1, now at v3"
 *     and "2 behind", because the number is the reason to look.
 *   • **The graph matches the table.** It is projected from the rows
 *     themselves, so a query returning a relation draws one, and a
 *     query returning counts draws nothing.
 *   • **A captured source is a question, not a fact.** Confirm / Not
 *     a source sit on the row, because only a confirmed edge raises a
 *     staleness warning later.
 *
 * The RPC stub logs every call to the pane at the bottom, so the
 * arguments each control sends can be checked by eye.
 */

