class ArtifactRpcHandler(RpcHandler):
    """Forwards each artifact RPC to the extension, or says why not.

    `read_file` and `search_code` are *not* artifact RPCs — they
    share the access model and nothing else — so they stay on igni
    and are declared here as they always were.
    """

    def methods(self) -> dict[RpcMethod, Callable[[dict], Any]]:
        routed: dict[RpcMethod, Callable[[dict], Any]] = {
            method: self._forwarder(method) for method in ARTIFACT_ROUTES
        }
        routed.update(super().methods())
        return routed

    def _forwarder(self, method: RpcMethod) -> Callable[[dict], Any]:
        route = ARTIFACT_ROUTES[method]

        async def forward(args: dict) -> Any:
            return await self._ask_the_extension(route, args)

        return forward

    async def _ask_the_extension(self, route: Routed, args: dict) -> Any:
        """Call `ext.igni.artifacts.<tool>` on this deployment's copy.

        Through `ExtensionRpc.dispatch` with the extension as its
        own caller, which is the same path its frame takes — so
        `permissions.rpc` is checked against the installed manifest
        rather than being skipped because the call came from
        inside igni.
        """
        extensions = self._ctx.extensions
        if extensions is None:
            raise ExtensionRefused(
                "This backend has no extension support, so there is nothing "
                "to answer document requests. Documents are an extension, and it "
                "arrives from the Artifacts service through igni server when you "
                "are signed in."
            )
        return await extensions.dispatch(
            caller=ARTIFACTS,
            method=f"ext.{ARTIFACTS}.{route.tool}",
            args=route.arguments(args),
        )

    @rpc(RpcMethod.READ_FILE)
    def read_file(self, args: dict) -> Any:
        return self._ctx.backend.read_file(args["path"])

    @rpc(RpcMethod.SEARCH_CODE)
    def search_code(self, args: dict) -> Any:
        return self._ctx.backend.search_code(args["query"])
