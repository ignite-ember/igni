logger = logging.getLogger(__name__)

#: The extension that answers these now.
ARTIFACTS = "igni.artifacts"


@dataclass(frozen=True, slots=True)
class Routed:
    """One legacy RPC, and the extension tool behind it."""

    #: The tool's name in `ext.igni.artifacts.<tool>`.
    tool: str
    #: Wire argument name -> the tool's parameter name. Empty for
    #: the forty that never needed one.
    renames: Mapping[str, str] = field(default_factory=dict)

    def arguments(self, args: Mapping[str, Any]) -> dict[str, Any]:
        """The client's arguments, under the names the tool takes.

        Unknown keys are passed through rather than dropped: the
        client may send something a newer extension understands and
        this file has never heard of, and silently removing it
        would make the extension's own contract depend on igni
        being up to date.
        """
        return {self.renames.get(key, key): value for key, value in args.items()}


